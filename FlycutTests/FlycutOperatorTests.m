//
//  FlycutOperatorTests.m
//  FlycutTests
//
//  Unit tests for FlycutOperator, the layer between AppController and the FlycutStores.
//
//  FlycutOperator reads and writes [NSUserDefaults standardUserDefaults] directly. Every key it
//  touches is snapshotted in setUp and restored in tearDown, and setUp pins each of them to a
//  known value so tests don't depend on run order or leftover state. Anything that could write a
//  file (savePreference, saveForgotten*, save/autoSave locations) is either off or pointed at a
//  per-test temporary directory that is removed in tearDown. No alert delegate is installed
//  unless a test supplies a fake one, so no NSAlert or NSSavePanel can be shown.
//

#import <XCTest/XCTest.h>
#import "FlycutOperator.h"

static NSString *const kTestType = @"public.utf8-plain-text";
static NSString *const kTestAppName = @"TestApp";
static NSString *const kTestAppBundleURL = @"/Applications/TestApp.app";

#pragma mark - Test doubles

// Stands in for AppController's savePreferencesOnDict:, which saveEngine calls before persisting.
@interface FOTSaveTarget : NSObject
@property (nonatomic) NSUInteger saveCount;
@property (nonatomic, strong) NSMutableDictionary *lastDict;
- (void)savePreferencesOnDict:(NSMutableDictionary *)saveDict;
@end

@implementation FOTSaveTarget
- (void)savePreferencesOnDict:(NSMutableDictionary *)saveDict
{
	self.saveCount++;
	self.lastDict = saveDict;
	[saveDict setObject:@"fromSaveTarget" forKey:@"testMarker"];
}
@end

// Stands in for AppController's updateMenu, the clippingAddedSelector.
@interface FOTClippingAddedTarget : NSObject
@property (nonatomic) NSUInteger addedCount;
- (void)clippingAdded;
@end

@implementation FOTClippingAddedTarget
- (void)clippingAdded
{
	self.addedCount++;
}
@end

// Answers FlycutOperator's alerts with a fixed button title instead of showing UI.
@interface FOTAlertDelegate : NSObject <FlycutOperatorDelegate>
@property (nonatomic, copy) NSString *answer;
@property (nonatomic) NSUInteger alertCount;
@property (nonatomic, copy) NSArray *lastButtons;
@end

@implementation FOTAlertDelegate
- (NSString *)alertWithMessageText:(NSString *)message informationText:(NSString *)information buttonsTexts:(NSArray *)buttons
{
	self.alertCount++;
	self.lastButtons = buttons;
	return self.answer;
}
@end

#pragma mark - Tests

@interface FlycutOperatorTests : XCTestCase
@property (nonatomic, strong) NSMutableDictionary *savedDefaults;
@property (nonatomic) BOOL domainExisted;
@property (nonatomic, strong) FOTSaveTarget *saveTarget;
@property (nonatomic, strong) FOTClippingAddedTarget *addedTarget;
@property (nonatomic, copy) NSString *tempDirectory;
@end

@implementation FlycutOperatorTests

+ (NSArray<NSString *> *)defaultsKeys
{
	return @[@"rememberNum", @"favoritesRememberNum", @"savePreference", @"store",
			 @"skipPasswordFields", @"skipPboardTypes", @"skipPboardTypesList",
			 @"skipPasswordLengths", @"skipPasswordLengthsList", @"revealPasteboardTypes",
			 @"removeDuplicates", @"pasteMovesToTop", @"syncSettingsViaICloud",
			 @"syncClippingsViaICloud", @"wraparoundBezel", @"stifleRememberResizeWarning",
			 @"saveForgottenClippings", @"saveForgottenFavorites", @"saveToLocation",
			 @"autoSaveToLocation", @"displayNum", @"displayLen"];
}

- (void)setUp
{
	[super setUp];
	NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];

	// Snapshot what is in the persistent domain (not registered defaults) so tearDown can put it back.
	NSString *domainName = [[NSBundle mainBundle] bundleIdentifier];
	NSDictionary *domain = domainName ? [defaults persistentDomainForName:domainName] : nil;
	self.domainExisted = (domain != nil);
	self.savedDefaults = [NSMutableDictionary dictionary];
	for (NSString *key in [[self class] defaultsKeys]) {
		// Read the persistent domain only, so registered defaults are never copied into it on restore.
		id value = domainName ? domain[key] : [defaults objectForKey:key];
		self.savedDefaults[key] = value ?: [NSNull null];
	}

	self.tempDirectory = [NSTemporaryDirectory() stringByAppendingPathComponent:
						  [NSString stringWithFormat:@"FlycutOperatorTests-%@", [NSUUID UUID].UUIDString]];
	[[NSFileManager defaultManager] createDirectoryAtPath:self.tempDirectory
							  withIntermediateDirectories:YES attributes:nil error:nil];

	// Pin every key to a known, file-free state.
	[defaults setInteger:0 forKey:@"savePreference"];
	[defaults setObject:@{} forKey:@"store"];
	[defaults setInteger:40 forKey:@"rememberNum"];
	[defaults setInteger:40 forKey:@"favoritesRememberNum"];
	[defaults setBool:YES forKey:@"skipPasswordFields"];
	[defaults setBool:YES forKey:@"skipPboardTypes"];
	[defaults setObject:@"PasswordPboardType,org.nspasteboard.TransientType,org.nspasteboard.ConcealedType,org.nspasteboard.AutoGeneratedType,com.agilebits.onepassword"
				 forKey:@"skipPboardTypesList"];
	[defaults setBool:NO forKey:@"skipPasswordLengths"];
	[defaults setObject:@"12, 20, 32" forKey:@"skipPasswordLengthsList"];
	[defaults setBool:NO forKey:@"revealPasteboardTypes"];
	[defaults setBool:NO forKey:@"removeDuplicates"];
	[defaults setBool:NO forKey:@"pasteMovesToTop"];
	[defaults setBool:NO forKey:@"syncSettingsViaICloud"];
	[defaults setBool:NO forKey:@"syncClippingsViaICloud"];
	[defaults setBool:NO forKey:@"wraparoundBezel"];
	[defaults setBool:NO forKey:@"stifleRememberResizeWarning"];
	[defaults setBool:NO forKey:@"saveForgottenClippings"];
	[defaults setBool:NO forKey:@"saveForgottenFavorites"];
	[defaults setInteger:10 forKey:@"displayNum"];
	[defaults setInteger:40 forKey:@"displayLen"];
	// Safety net: even an unexpected save lands in the temp directory, never on the Desktop.
	NSURL *tempURL = [NSURL fileURLWithPath:self.tempDirectory isDirectory:YES];
	[defaults setURL:tempURL forKey:@"saveToLocation"];
	[defaults setURL:tempURL forKey:@"autoSaveToLocation"];

	self.saveTarget = [[FOTSaveTarget alloc] init];
	self.addedTarget = [[FOTClippingAddedTarget alloc] init];
}

- (void)tearDown
{
	NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
	[self.savedDefaults enumerateKeysAndObjectsUsingBlock:^(NSString *key, id value, BOOL *stop) {
		if (value == [NSNull null])
			[defaults removeObjectForKey:key];
		else
			[defaults setObject:value forKey:key];
	}];
	// Don't leave behind an empty preferences domain that didn't exist before the test.
	NSString *domainName = [[NSBundle mainBundle] bundleIdentifier];
	if (domainName && !self.domainExisted && [defaults persistentDomainForName:domainName].count == 0)
		[defaults removePersistentDomainForName:domainName];
	[[NSFileManager defaultManager] removeItemAtPath:self.tempDirectory error:nil];
	[super tearDown];
}

#pragma mark Helpers

// Builds an operator the way AppController does: init, then awakeFromNib with a save target.
- (FlycutOperator *)makeOperator
{
	FlycutOperator *op = [[FlycutOperator alloc] init];
	[op awakeFromNibDisplaying:10
			 withDisplayLength:40
			  withSaveSelector:@selector(savePreferencesOnDict:)
					 forTarget:self.saveTarget];
	return op;
}

- (bool)add:(NSString *)contents to:(FlycutOperator *)op
{
	return [op addClipping:contents
					ofType:kTestType
				   fromApp:kTestAppName
		  withAppBundleURL:kTestAppBundleURL
					target:self.addedTarget
	 clippingAddedSelector:@selector(clippingAdded)];
}

// Adds the strings in order, so the last one ends up most recent (stack position 0).
- (FlycutOperator *)operatorWithClippings:(NSArray<NSString *> *)contents
{
	FlycutOperator *op = [self makeOperator];
	for (NSString *s in contents)
		[self add:s to:op];
	return op;
}

- (NSArray<NSString *> *)contentsOf:(FlycutOperator *)op
{
	NSMutableArray *result = [NSMutableArray array];
	for (int i = 0; i < [op jcListCount]; i++)
		[result addObject:[op clippingStringWithCount:i]];
	return result;
}

- (NSArray<NSString *> *)filesUnderTempDirectory
{
	NSMutableArray *files = [NSMutableArray array];
	NSDirectoryEnumerator *e = [[NSFileManager defaultManager] enumeratorAtPath:self.tempDirectory];
	for (NSString *relative in e) {
		if ([relative.pathExtension isEqualToString:@"txt"])
			[files addObject:[self.tempDirectory stringByAppendingPathComponent:relative]];
	}
	return files;
}

- (BOOL)skip:(NSString *)contents types:(NSArray<NSString *> *)types
{
	FlycutOperator *op = [self makeOperator];
	return [op shouldSkip:contents ofType:@"public.utf8-plain-text" fromAvailableTypes:types];
}

#pragma mark - addClipping

- (void)testAddClippingPutsNewestAtTopAndNotifiesTarget
{
	FlycutOperator *op = [self makeOperator];

	XCTAssertTrue([self add:@"first" to:op]);
	XCTAssertTrue([self add:@"second" to:op]);

	XCTAssertEqual([op jcListCount], 2);
	XCTAssertEqualObjects([self contentsOf:op], (@[@"second", @"first"]));
	XCTAssertEqual(self.addedTarget.addedCount, 2u);
	FlycutClipping *top = [op clippingAtStackPosition];
	XCTAssertEqualObjects([top type], kTestType);
	XCTAssertEqualObjects([top appLocalizedName], kTestAppName);
	XCTAssertEqualObjects([top appBundleURL], kTestAppBundleURL);
	XCTAssertGreaterThan([top timestamp], 0);
}

